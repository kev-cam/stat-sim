-- ble_phy_pkg: the Bluetooth LE physical layer's bit handling (Core Specification 6.1, Vol 6 Parts A and B),
-- the VHDL of ble_phy.py: channels, packets of the four PHYs (LE 1M, LE 2M, LE Coded S=2 and S=8),
-- whitening, CRC, the Coded PHY's convolutional code and pattern mapper, and the two detectors a
-- receiver needs (a four-state sequence detector for the discriminator's output, and a soft Viterbi
-- decoder).  Bits are in transmission order throughout (an octet's least significant bit first).
--
-- ble_phy.py's `check` reproduces the specification's sample data; tb_cc2652r.vhd checks this package
-- against ble_phy.py (packets generated by cc2652r_vhdl.py).
library ieee;
use ieee.math_real.all;

package ble_phy_pkg is
    type ble_phy is (PHY_1M, PHY_2M, PHY_S2, PHY_S8);
    subtype ble_octet is natural range 0 to 255;
    type ble_octets is array (natural range <>) of ble_octet;
    constant BLE_MAX_PDU : positive := 257;                 -- header (2) and up to 255 octets of payload

    constant BLE_ADV_AA  : bit_vector(0 to 31);             -- 0x8E89BED6, advertising physical channel
    constant BLE_TEST_AA : bit_vector(0 to 31);             -- 0x71764129, Direct Test Mode
    constant BLE_CRC_INIT_ADV : natural := 16#555555#;
    constant BLE_T_IFS : time := 150 us;

    -- advertising physical channel PDU types
    constant BLE_ADV_IND : natural := 0;
    constant BLE_ADV_DIRECT_IND : natural := 1;
    constant BLE_ADV_NONCONN_IND : natural := 2;
    constant BLE_SCAN_REQ : natural := 3;
    constant BLE_SCAN_RSP : natural := 4;
    constant BLE_CONNECT_IND : natural := 5;
    constant BLE_ADV_SCAN_IND : natural := 6;

    function ble_symbol_rate(phy : ble_phy) return real;
    function ble_coding(phy : ble_phy) return positive;                     -- S: 1 uncoded, 2, 8
    function ble_channel_frequency(index : natural) return real;           -- channel index (37 - 39 advertise)
    function ble_rf_channel_frequency(k : natural) return real;            -- RF channel: 2402 + 2 k MHz

    function ble_bits_of(o : ble_octets) return bit_vector;
    function ble_octets_of(b : bit_vector) return ble_octets;
    function ble_bits_of_hex(h : string) return bit_vector;                -- "8E89BED6" -> 32 bits, LSB first
    function ble_whitening(channel : natural; n : natural) return bit_vector;
    function ble_crc24(b : bit_vector; init : natural) return bit_vector;
    function ble_fec_encode(b : bit_vector) return bit_vector;             -- encoder starts in state 0
    function ble_pattern_map(c : bit_vector; s : positive) return bit_vector;
    function ble_coded_block1(aa : bit_vector(0 to 31); s : positive) return bit_vector;
    -- the symbols on the air of one packet; channel: the index that whitens PDU and CRC, -1: not whitened
    function ble_packet_symbols(phy : ble_phy; pdu : ble_octets; channel : integer; aa : bit_vector(0 to 31);
                                crc_init : natural) return bit_vector;
    function ble_packet_symbol_count(phy : ble_phy; pdu_len : natural) return natural;
    -- what a receiver looks for: preamble and access address (Coded: preamble and the coded access address)
    function ble_sync_pattern(phy : ble_phy; aa : bit_vector(0 to 31)) return bit_vector;

    function ble_adv_pdu(pdu_type : natural; payload : ble_octets; tx_add, rx_add : natural := 0) return ble_octets;
    function ble_prbs9(n : natural) return bit_vector;
    function ble_test_pdu(length : natural) return ble_octets;             -- Direct Test Mode, PRBS9 payload

    -- soft(k) = t0 m(k-1) + t1 m(k) + t2 m(k+1) + noise, m = +-1: the most likely sequence
    function ble_sequence_detect(soft : real_vector; t0, t1, t2 : real) return bit_vector;
    -- soft symbols (positive: 1) of pattern-mapped coded bits -> (a0, a1) pairs for the decoder
    function ble_pattern_llr(soft : real_vector; s : positive) return real_vector;
    function ble_viterbi(llr : real_vector; terminated : boolean := true) return bit_vector;
end package;

package body ble_phy_pkg is
    function ble_bits_of_hex(h : string) return bit_vector is
        variable r : bit_vector(0 to 4 * h'length - 1);
        variable v, n : natural;
    begin
        n := 0;
        for i in h'reverse_range loop                    -- last digit is the least significant
            case h(i) is
                when '0' to '9' => v := character'pos(h(i)) - character'pos('0');
                when 'A' to 'F' => v := character'pos(h(i)) - character'pos('A') + 10;
                when 'a' to 'f' => v := character'pos(h(i)) - character'pos('a') + 10;
                when others => report "ble_bits_of_hex: not a hex digit" severity failure;
            end case;
            for b in 0 to 3 loop
                if (v / 2 ** b) mod 2 = 1 then
                    r(n) := '1';
                else
                    r(n) := '0';
                end if;
                n := n + 1;
            end loop;
        end loop;
        return r;
    end function;

    constant BLE_ADV_AA  : bit_vector(0 to 31) := ble_bits_of_hex("8E89BED6");
    constant BLE_TEST_AA : bit_vector(0 to 31) := ble_bits_of_hex("71764129");

    function ble_symbol_rate(phy : ble_phy) return real is
    begin
        if phy = PHY_2M then
            return 2.0e6;
        end if;
        return 1.0e6;
    end function;

    function ble_coding(phy : ble_phy) return positive is
    begin
        case phy is
            when PHY_S2 => return 2;
            when PHY_S8 => return 8;
            when others => return 1;
        end case;
    end function;

    function ble_channel_frequency(index : natural) return real is
    begin
        case index is
            when 37 => return 2402.0e6;
            when 38 => return 2426.0e6;
            when 39 => return 2480.0e6;
            when 0 to 10 => return 2404.0e6 + 2.0e6 * real(index);
            when 11 to 36 => return 2428.0e6 + 2.0e6 * real(index - 11);
            when others =>
                report "ble_channel_frequency: channel index " & integer'image(index) severity failure;
                return 0.0;
        end case;
    end function;

    function ble_rf_channel_frequency(k : natural) return real is
    begin
        assert k <= 39 report "ble_rf_channel_frequency: RF channel " & integer'image(k) severity failure;
        return 2402.0e6 + 2.0e6 * real(k);
    end function;

    function ble_bits_of(o : ble_octets) return bit_vector is
        variable r : bit_vector(0 to 8 * o'length - 1);
        variable n : natural := 0;
    begin
        for i in o'range loop
            for b in 0 to 7 loop
                if (o(i) / 2 ** b) mod 2 = 1 then
                    r(n) := '1';
                else
                    r(n) := '0';
                end if;
                n := n + 1;
            end loop;
        end loop;
        return r;
    end function;

    function ble_octets_of(b : bit_vector) return ble_octets is
        alias x : bit_vector(0 to b'length - 1) is b;
        variable r : ble_octets(0 to b'length / 8 - 1);
        variable v : natural;
    begin
        for i in r'range loop
            v := 0;
            for k in 7 downto 0 loop
                v := 2 * v;
                if x(8 * i + k) = '1' then
                    v := v + 1;
                end if;
            end loop;
            r(i) := v;
        end loop;
        return r;
    end function;

    -- x^7 + x^4 + 1; position 0 set, the channel index in positions 1 .. 6 with its MSB in position 1
    function ble_whitening(channel : natural; n : natural) return bit_vector is
        variable reg : bit_vector(0 to 6);
        variable r : bit_vector(0 to n - 1);
        variable o : bit;
    begin
        reg(0) := '1';
        for i in 0 to 5 loop
            if (channel / 2 ** (5 - i)) mod 2 = 1 then
                reg(i + 1) := '1';
            else
                reg(i + 1) := '0';
            end if;
        end loop;
        for i in r'range loop
            o := reg(6);
            r(i) := o;
            reg := (o, reg(0), reg(1), reg(2), reg(3) xor o, reg(4), reg(5));
        end loop;
        return r;
    end function;

    -- x^24 + x^10 + x^9 + x^6 + x^4 + x^3 + x + 1, the register's most significant position sent first
    function ble_crc24(b : bit_vector; init : natural) return bit_vector is
        variable crc : bit_vector(23 downto 0);
        variable fb : bit;
        variable r : bit_vector(0 to 23);
        constant poly : bit_vector(23 downto 0) := x"00065B";
    begin
        for i in 0 to 23 loop
            if (init / 2 ** i) mod 2 = 1 then
                crc(i) := '1';
            else
                crc(i) := '0';
            end if;
        end loop;
        for i in b'range loop
            fb := crc(23) xor b(i);
            crc := crc(22 downto 0) & '0';
            if fb = '1' then
                crc := crc xor poly;
            end if;
        end loop;
        for i in 0 to 23 loop
            r(i) := crc(23 - i);
        end loop;
        return r;
    end function;

    -- G0 = 1 + D + D^2 + D^3, G1 = 1 + D^2 + D^3, a0 before a1
    function ble_fec_encode(b : bit_vector) return bit_vector is
        alias x : bit_vector(0 to b'length - 1) is b;
        variable r : bit_vector(0 to 2 * b'length - 1);
        variable d1, d2, d3 : bit := '0';
    begin
        for i in x'range loop
            r(2 * i) := x(i) xor d1 xor d2 xor d3;
            r(2 * i + 1) := x(i) xor d2 xor d3;
            d3 := d2;
            d2 := d1;
            d1 := x(i);
        end loop;
        return r;
    end function;

    function ble_pattern_map(c : bit_vector; s : positive) return bit_vector is
        alias x : bit_vector(0 to c'length - 1) is c;
        variable r : bit_vector(0 to 4 * c'length - 1);
    begin
        if s = 2 then
            return x;
        end if;
        for i in x'range loop
            r(4 * i) := x(i);
            r(4 * i + 1) := x(i);
            r(4 * i + 2) := not x(i);
            r(4 * i + 3) := not x(i);
        end loop;
        return r;
    end function;

    function ble_coded_block1(aa : bit_vector(0 to 31); s : positive) return bit_vector is
        variable b : bit_vector(0 to 36) := (others => '0');       -- access address, CI (2), TERM1 (3)
    begin
        b(0 to 31) := aa;
        if s /= 8 then
            b(32) := '1';
        end if;
        return ble_pattern_map(ble_fec_encode(b), 8);
    end function;

    function ble_packet_symbol_count(phy : ble_phy; pdu_len : natural) return natural is
        constant s : positive := ble_coding(phy);
    begin
        case phy is
            when PHY_1M => return 8 + 32 + 8 * pdu_len + 24;
            when PHY_2M => return 16 + 32 + 8 * pdu_len + 24;
            when others => return 80 + 296 + (8 * pdu_len + 24 + 3) * s;
        end case;
    end function;

    function ble_packet_symbols(phy : ble_phy; pdu : ble_octets; channel : integer; aa : bit_vector(0 to 31);
                                crc_init : natural) return bit_vector is
        constant nb : natural := 8 * pdu'length;
        constant s : positive := ble_coding(phy);
        variable bdy : bit_vector(0 to nb + 23);
        variable r : bit_vector(0 to ble_packet_symbol_count(phy, pdu'length) - 1);
        variable b2 : bit_vector(0 to nb + 26) := (others => '0');
        variable npre : natural;
    begin
        bdy(0 to nb - 1) := ble_bits_of(pdu);
        bdy(nb to nb + 23) := ble_crc24(bdy(0 to nb - 1), crc_init);
        if channel >= 0 then
            bdy := bdy xor ble_whitening(channel, nb + 24);
        end if;
        if s = 1 then
            npre := 8;
            if phy = PHY_2M then
                npre := 16;
            end if;
            for i in 0 to npre - 1 loop                 -- alternating, starting as the access address does
                if i mod 2 = 0 then
                    r(i) := aa(0);
                else
                    r(i) := not aa(0);
                end if;
            end loop;
            r(npre to npre + 31) := aa;
            r(npre + 32 to r'high) := bdy;
            return r;
        end if;
        for i in 0 to 79 loop                           -- 00111100 ten times
            if i mod 8 >= 2 and i mod 8 <= 5 then
                r(i) := '1';
            else
                r(i) := '0';
            end if;
        end loop;
        r(80 to 375) := ble_coded_block1(aa, s);
        b2(0 to nb + 23) := bdy;
        r(376 to r'high) := ble_pattern_map(ble_fec_encode(b2), s);
        return r;
    end function;

    function ble_sync_pattern(phy : ble_phy; aa : bit_vector(0 to 31)) return bit_vector is
        constant none : ble_octets(0 to 1) := (0, 0);
        constant p : bit_vector := ble_packet_symbols(phy, none, -1, aa, BLE_CRC_INIT_ADV);
    begin
        case phy is
            when PHY_1M => return p(0 to 39);
            when PHY_2M => return p(0 to 47);
            when others => return p(0 to 335);          -- block 1's access address part does not depend on S
        end case;
    end function;

    function ble_adv_pdu(pdu_type : natural; payload : ble_octets; tx_add, rx_add : natural := 0) return ble_octets is
        variable r : ble_octets(0 to payload'length + 1);
    begin
        r(0) := pdu_type + 64 * tx_add + 128 * rx_add;
        r(1) := payload'length;
        r(2 to r'high) := payload;
        return r;
    end function;

    -- x^9 + x^5 + 1, all ones to start
    function ble_prbs9(n : natural) return bit_vector is
        variable reg : bit_vector(8 downto 0) := (others => '1');
        variable r : bit_vector(0 to n - 1);
    begin
        for i in r'range loop
            r(i) := reg(0);
            reg := (reg(0) xor reg(4)) & reg(8 downto 1);
        end loop;
        return r;
    end function;

    function ble_test_pdu(length : natural) return ble_octets is
        variable r : ble_octets(0 to length + 1);
    begin
        r(0) := 0;                                      -- payload type: PRBS9
        r(1) := length;
        r(2 to r'high) := ble_octets_of(ble_prbs9(8 * length));
        return r;
    end function;

    function ble_sequence_detect(soft : real_vector; t0, t1, t2 : real) return bit_vector is
        alias x : real_vector(0 to soft'length - 1) is soft;
        type choice_t is array (natural range <>, natural range <>) of boolean;
        variable choice : choice_t(0 to soft'length - 1, 0 to 3);
        type r42 is array (0 to 3, 0 to 1) of real;
        variable expect : r42;
        variable pm, nx : real_vector(0 to 3) := (others => 0.0);
        variable c0, c1, e : real;
        variable state, xb : natural;
        variable r : bit_vector(0 to soft'length - 1);
        constant m : real_vector(0 to 1) := (-1.0, 1.0);
    begin
        -- new state sp = b(k) + 2 b(k+1), from state xb + 2 b(k)
        for sp in 0 to 3 loop
            for xv in 0 to 1 loop
                expect(sp, xv) := t0 * m(xv) + t1 * m(sp mod 2) + t2 * m(sp / 2);
            end loop;
        end loop;
        for k in x'range loop
            for sp in 0 to 3 loop
                e := x(k) - expect(sp, 0);
                c0 := pm(2 * (sp mod 2)) - e * e;
                e := x(k) - expect(sp, 1);
                c1 := pm(1 + 2 * (sp mod 2)) - e * e;
                choice(k, sp) := c1 > c0;
                if c1 > c0 then
                    nx(sp) := c1;
                else
                    nx(sp) := c0;
                end if;
            end loop;
            pm := nx;
        end loop;
        state := 0;
        for sp in 1 to 3 loop
            if pm(sp) > pm(state) then
                state := sp;
            end if;
        end loop;
        for k in x'reverse_range loop
            if state mod 2 = 1 then
                r(k) := '1';
            else
                r(k) := '0';
            end if;
            xb := 0;
            if choice(k, state) then
                xb := 1;
            end if;
            state := xb + 2 * (state mod 2);
        end loop;
        return r;
    end function;

    function ble_pattern_llr(soft : real_vector; s : positive) return real_vector is
        alias x : real_vector(0 to soft'length - 1) is soft;
        variable r : real_vector(0 to soft'length / 4 - 1);
    begin
        if s /= 8 then
            return x;
        end if;
        for i in r'range loop
            r(i) := x(4 * i) + x(4 * i + 1) - x(4 * i + 2) - x(4 * i + 3);
        end loop;
        return r;
    end function;

    function ble_viterbi(llr : real_vector; terminated : boolean := true) return bit_vector is
        alias x : real_vector(0 to llr'length - 1) is llr;
        constant n : natural := llr'length / 2;
        type choice_t is array (natural range <>, natural range <>) of boolean;
        variable choice : choice_t(0 to n - 1, 0 to 7);
        type r82 is array (0 to 7, 0 to 1) of real;
        type n82 is array (0 to 7, 0 to 1) of natural;
        variable s0, s1 : r82;
        variable prev : n82;
        variable pm, nx : real_vector(0 to 7) := (others => -1.0e30);
        variable c0, c1 : real;
        variable state, p, b, d1, d2, d3 : natural;
        variable r : bit_vector(0 to n - 1);
    begin
        for sp in 0 to 7 loop
            for xv in 0 to 1 loop
                p := sp / 2 + 4 * xv;                   -- the state before: the newest bit is bit 0
                prev(sp, xv) := p;
                b := sp mod 2;
                d1 := p mod 2;
                d2 := (p / 2) mod 2;
                d3 := p / 4;
                s0(sp, xv) := 2.0 * real((b + d1 + d2 + d3) mod 2) - 1.0;
                s1(sp, xv) := 2.0 * real((b + d2 + d3) mod 2) - 1.0;
            end loop;
        end loop;
        pm(0) := 0.0;
        for k in 0 to n - 1 loop
            for sp in 0 to 7 loop
                c0 := pm(prev(sp, 0)) + s0(sp, 0) * x(2 * k) + s1(sp, 0) * x(2 * k + 1);
                c1 := pm(prev(sp, 1)) + s0(sp, 1) * x(2 * k) + s1(sp, 1) * x(2 * k + 1);
                choice(k, sp) := c1 > c0;
                if c1 > c0 then
                    nx(sp) := c1;
                else
                    nx(sp) := c0;
                end if;
            end loop;
            pm := nx;
        end loop;
        state := 0;
        if not terminated then
            for sp in 1 to 7 loop
                if pm(sp) > pm(state) then
                    state := sp;
                end if;
            end loop;
        end if;
        for k in n - 1 downto 0 loop
            if state mod 2 = 1 then
                r(k) := '1';
            else
                r(k) := '0';
            end if;
            if choice(k, state) then
                state := state / 2 + 4;
            else
                state := state / 2;
            end if;
        end loop;
        return r;
    end function;
end package body;
