"""Resample fitted rffit.py fundamental-gain tables onto a uniform |a| grid for the pipeline benchmark."""
import json, sys
import numpy as np
N = 256
def table(path, freq):
    m = json.load(open(path))
    pf = min(m["per_freq"], key=lambda p: abs(p["freq"] - freq))["harm"]["1"]
    mag = np.array(pf["table_mag"]); G = np.array(pf["table_re"]) + 1j * np.array(pf["table_im"])
    g = np.linspace(0, mag.max(), N)
    return mag.max(), np.interp(g, mag, G.real), np.interp(g, mag, G.imag)
out = [f"// generated by gen_tables.py from ../models\n#define TAB_N {N}"]
for name, path, f in (("PA", "../models/classe_pa.json", 850e6), ("LNA", "../models/ft8_lna4_ext.json", 28e6)):
    amax, re, im = table(path, f)
    out.append(f"static const float {name}_AMAX = {amax:.9e}f;")
    out.append(f"static const float {name}_TAB[2 * TAB_N] = {{" + ", ".join(f"{a:.8e}f, {b:.8e}f" for a, b in zip(re, im)) + "};")
open("tables.h", "w").write("\n".join(out) + "\n")
