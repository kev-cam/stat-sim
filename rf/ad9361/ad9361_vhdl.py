"""
ad9361_vhdl.py -- write ad9361_pkg.vhd, the AD9361 model for nvc, from the tables in ad9361.py.

    ad9361_vhdl.py emit [-o ad9361_pkg.vhd]   write the package
    ad9361_vhdl.py check [--nvc PATH]         compile it with tb_ad9361.vhd, run, compare with ad9361.py

The package has the data sheet tables (SPEC, SCALARS), the model's assumptions (MODEL) and the
sample-by-sample part of the Python model on nvc's rf.rf_signal_pkg / rf.iq_pkg types:
  ad9361_tx_ideal / ad9361_rx_ideal    the noise-free memoryless paths (DAC word, attenuator,
                                       compression; compression, gain, ADC), bit-exact with Python
  ad9361_tx_sample / ad9361_rx_sample  the same with thermal / TX noise, LO phase noise, the EVM
                                       residual, carrier leakage and quadrature errors
  ad9361_agc_slow                      the slow-attack gain decision
Not in the VHDL package: the baseband filter response, the fast-attack AGC, the buffers and the
Arena (use rf's antenna and channel components for the air).
"""
