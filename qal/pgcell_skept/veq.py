"""(c) INDEPENDENT EQUIVALENCE RE-CHECK of the Phase-2 remap.

Independence, stated plainly:
  * cell Boolean models are GENERATED from the PDK liberty file's own
    `function :` attributes (libfun.py), NOT read from the run's minicells.v.
    The run's minicells.v is then diffed against mine as a separate check.
  * the pass-gate cells pg_xor2/pg_xnor2/pg_mux2 are written here from their
    NAME semantics and cross-checked against the PDK cells they replace.
  * the golden is a pure-Python model of the RTL equations in sha_slice.v,
    written here, plus yosys' own RTL elaboration for the SAT miter.
  * SAT miter (E1) and equiv_induct (E2) are run by me, on the netlists the
    run produced, with my models.
  * the vector run (E3) uses iverilog with my models.
"""
