    for c in CELLS_WANT:
        m = re.search(r"module %s\s*\(([^)]*)\).*?assign (\w+) = ([^;]+);" % c,
                      mini, re.S)
        R["minicells_agreement"][c] = (m.group(3).strip() if m else None)

    nets = sys.argv[1:] or ["cmos", "pgp", "pgp1", "pgp1c", "pgp2", "pgp2c",
                            "pgr1", "pgr1c", "abc_nand_resyn2", "abc_pg_resyn2"]
    R["netlists"] = {}
    for n in nets:
        net = CMOS if n == "cmos" else os.path.join(OUT, "sha_slice.%s.v" % n)
        if not os.path.exists(net):
            R["netlists"][n] = dict(error="missing %s" % net)
            continue
        t0 = time.monotonic()
        d = dict(path=net)
        d.update(formal(n, net, models))
        d["E3_vectors"] = vectors(n, net, models)
        d["wall_s"] = round(time.monotonic() - t0, 1)
        d["PASS"] = bool(d["E1_sat"]["pass_"] and d["E2_induct"]["pass_"]
                         and d["E3_vectors"].get("pass_"))
        R["netlists"][n] = d
        print("%-18s E1=%s E2=%s E3=%s/%s  %.0fs" %
              (n, d["E1_sat"]["pass_"], d["E2_induct"]["pass_"],
               d["E3_vectors"].get("vectors"), d["E3_vectors"].get("mismatches"),
               d["wall_s"]), flush=True)
    json.dump(R, open(os.path.join(HERE, "VEQ.json"), "w"), indent=1)
    print("wrote VEQ.json")
